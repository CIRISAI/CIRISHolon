"""
species.py -- the staked species of ELEMENTS-1, their grids, and the derivation
of each one's ground Sz.

GROUND Sz IS DERIVED, NOT ASSUMED.  Every Sz sector allowed by the electron
count and the orbital count is solved, and the ground total spin is read off the
degeneracy pattern: a multiplet of total spin S appears, with the same energy,
in every sector with |Sz| <= S and in none above, so

        S  =  max { Sz : E_min(Sz) = E_min(global) }.

The FCI is then run in the Sz = 0 sector for even electron counts and Sz = 1/2
for odd ones (the smallest sector that still contains the ground multiplet),
and the derived S is recorded with the energies of every sector that produced
it, so the reader can check the derivation rather than trust the label.

GRIDS ARE A DESIGN CHOICE, STAKED BEFORE THE ENERGIES ARE SEEN, not a result.
The ranges below are chosen wide enough to contain the repulsive wall and to
reach the separated-atom limit; nothing about where a minimum falls, or whether
one exists at all, is put in by hand.

Density differs between species, and the reason is compute, not physics: a
14400-determinant point costs about 950 seconds at the working precision, so the
three expensive species carry far fewer geometries than the cheap ones.  Li2 was
staked and largely computed before that cost was measured and keeps its denser
grid; N2 and CO carry a coarser base with the well window split more finely,
which is where the density actually earns its keep.  The per-species grid is
recorded in the artifact, so nothing about it is implicit.
"""

