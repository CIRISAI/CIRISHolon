GRID_DPS = 60


def sparse_subset(grid, well, spec):
    """Decimate a staked grid to a sparse STAKED SUBSET.

    THE RULE, STATED IN ADVANCE AND USING ONLY STAKED DESIGN PARAMETERS.  Keep
    a grid point when its index is divisible by a stride -- every second point
    inside the staked well window, every third outside it -- and always keep the
    first and last point so the repulsive wall and the separated-atom limit are
    both present.  The well window is itself a design input frozen before any
    energy was computed, so nothing here consults a result: the subset is a
    function of the grid rule and the window alone, and can be regenerated by
    anyone from those two.  It is manifestly not a choice of which points to
    show.

    WHY A SUBSET AT ALL.  A 14400-determinant geometry costs about 950 seconds
    at the working precision, and N2 and CO are the two species where that is
    unaffordable at full grid density on a shared machine.  The response is to
    take FEWER points, never cheaper ones: every emitted point is the same
    exact-in-model full CI in the same 14400-determinant space at the same 50
    digits, dual-route and certified.  A sparse exact referee is a referee; a
    dense approximate one is not.
    """
    from mpmath import mp as _mp
    lo, hi = mpf(well[0]), mpf(well[1])
    keep = {0, len(grid) - 1}
    for i, rs in enumerate(grid):
        r = mpf(rs)
        stride = (spec["well_stride"] if lo <= r <= hi
                  else spec["tail_stride"])
        if i % stride == 0:
            keep.add(i)
    return [grid[i] for i in sorted(keep)]


def grid_for(name):
    """The staked grid.  Built at a pinned precision so that the same species
    yields the same grid whatever precision the caller happens to be in --
    otherwise a stencil worker at dps 95 and an assembler at dps 60 would
    disagree about where the points are."""
    from mpmath import mp as _mp
    d = DIATOMICS[name]
    old = _mp.dps
    _mp.dps = GRID_DPS
    try:
        g = curve.build_grid(d["rmin"], d["rmax"], d["nbase"], d["well"],
                             d["nsplit"])
        if d.get("sparse"):
            g = sparse_subset(g, d["well"], d["sparse"])
        return g
    finally:
        _mp.dps = old


def sz_sectors(nelec, norb):
    """Every Sz sector the electron and orbital counts allow, as (2Sz, na, nb)."""
    out = []
    for two_sz in range(nelec % 2, nelec + 1, 2):
        na = (nelec + two_sz) // 2
        nb = nelec - na
        if na > norb or nb < 0 or nb > norb:
            continue
        out.append((two_sz, na, nb))
    return out


def ground_spin_from_sectors(energies, tol):
    """S = max{Sz : E_min(Sz) = E_min(global)}, as 2S.

    energies: {two_sz: E}.  tol: the degeneracy tolerance (the certified
    eigenvalue accuracy, not a fudge factor).
    """
    emin = min(energies.values())
    hit = [k for k, v in energies.items() if abs(v - emin) <= tol]
    return max(hit), emin, sorted(hit)
