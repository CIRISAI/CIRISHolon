def run_n(n, exhaustive, do_views):
    import math
    fam = family(n)
    W = len(fam)
    by_m = {}
    for x in fam:
        by_m.setdefault(x[1], []).append(x)
    # The cross-macro separation witness depends only on the pair of macro maps,
    # so it is exhibited once per macro-map pair — exhaustive over every pair.
    for m1 in by_m:
        for m2 in by_m:
            if m1 != m2:
                void(cross_macro_witness(m1, m2) is not None,
                     f"n={n}: cross-macro pair with no depth-1 witness")
