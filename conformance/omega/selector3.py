    if do_views:
        labs = view_labels(2 * n)
        reps = {}
        for (T, m, c) in fam:
            reps.setdefault(label[T], (T, m, c))
        N = 2 * n
        # per-view precomputation shared by every orbit representative
        vnb = [max(lab) + 1 for lab in labs]
        vtype = []
        for lab in labs:
            sz = [0] * (max(lab) + 1)
            for v in lab:
                sz[v] += 1
            vtype.append(tuple(sorted(sz)))
        rep_lbls = list(reps.keys())
        hist_plain = {lb: {} for lb in rep_lbls}
        hist_typed = {lb: {} for lb in rep_lbls}
        ncl = {lb: 0 for lb in rep_lbls}
