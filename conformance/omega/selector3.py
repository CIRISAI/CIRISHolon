# =========================================================== the model family
def family(n):
    """All closed dynamics on n fibers of size 2, as permutation tuples of the
    2n states, tagged with their (m, c) coordinates."""
    out = []
    for m in permutations(range(n)):
        for c in product((0, 1), repeat=n):
            T = tuple(2 * m[s >> 1] + ((s & 1) ^ c[s >> 1]) for s in range(2 * n))
            out.append((T, m, c))
    return out


def cycles(m):
    seen, cyc = set(), []
    for i in range(len(m)):
        if i in seen:
            continue
        cy, j = [], i
        while j not in seen:
            seen.add(j)
            cy.append(j)
            j = m[j]
        cyc.append(cy)
    return cyc


def holonomy(m, c):
    """The conjugation-invariant label: the multiset of (cycle length, Z2
    holonomy of c around that cycle).  Conjugation shifts c by a coboundary,
    which leaves every cycle sum fixed — so this is a gauge invariant, never a
    class marginal (M-GAUGE-LAUNDER, M-LOOP-BLIND)."""
    return tuple(sorted((len(cy), sum(c[i] for i in cy) % 2) for cy in cycles(m)))


def fixed_point_free(m):
    return all(m[i] != i for i in range(len(m)))


def mechanism_predicts(m, c):
    """The STAKED mechanism, evaluated on (m, c) alone — no reference to any
    measured identity set."""
    return fixed_point_free(m) and all(h == 0 for _, h in holonomy(m, c))


def sections(T, n):
    """T-invariant transversals: one state per fiber, closed under T."""
    out = []
    for x in product((0, 1), repeat=n):
        X = frozenset(2 * i + x[i] for i in range(n))
        if {T[s] for s in X} == set(X):
            out.append(X)
    return out


def knobs_section(T, n):
    """A(T): the acts T's own sections implement.  Deduplicated — a repeated
    letter adds no words."""
    return sorted({tuple(T[s] if s in X else s for s in range(2 * n))
                   for X in sections(T, n)})


def knobs_view_aligned(T, n):
    """The provably powerless vocabulary (plant ii): T restricted to unions of
    view blocks.  Every such act is view-covariant, hence gauge-safe on a
    closed holon by Break.lean T3."""
    return sorted({tuple(T[s] if B[s >> 1] else s for s in range(2 * n))
                   for B in product((0, 1), repeat=n)})


# ==================================================== exact separation by BFS
def separates(knobs, T, Tp, n):
    """Exact over ALL experiment words: BFS the reachable state-pair relation."""
    N = 2 * n
    seen = bytearray(N * N)
    stack = []
    for s in range(N):
        seen[s * N + s] = 1
        stack.append((s, s))
    while stack:
        x, y = stack.pop()
        if (x >> 1) != (y >> 1):
            return True
        nx, ny = T[x], Tp[y]
        if not seen[nx * N + ny]:
            seen[nx * N + ny] = 1
            stack.append((nx, ny))
        for a in knobs:
            nx, ny = a[x], a[y]
            if not seen[nx * N + ny]:
                seen[nx * N + ny] = 1
                stack.append((nx, ny))
    return False


def cross_macro_witness(m, mp):
    """The depth-1 separation witness for candidates with different macro maps:
    the word [step] from any state of a fiber where the macro maps differ.
    Exhibited, not assumed."""
    for i in range(len(m)):
        if m[i] != mp[i]:
            return i
    return None


def ident_set(T, m, c, knobs, fam, n, exhaustive, by_m=None):
    """|Ident_{knobs}(T)| over the whole candidate family.

    exhaustive=True runs the pair-BFS against EVERY candidate (gate B0's
    literal reading).  exhaustive=False uses the exhibited depth-1 witness for
    different-macro candidates and BFS for the rest; at n = 3 and n = 4 both
    are run and required to agree."""
    cand = fam if exhaustive else by_m[m]
    return [(Tp, mp, cp) for (Tp, mp, cp) in cand
            if not separates(knobs, T, Tp, n)]


# ============================================== the view lattice (gate N2/S6)
def view_labels(k):
    """Every view on k states, as a label array — the restricted-growth strings,
    which enumerate set partitions exactly once each (Bell(k) of them)."""
    out, lab = [], [0] * k

    def rec(i, mx):
        if i == k:
            out.append(lab[:])
            return
        for v in range(mx + 2):
            lab[i] = v
            rec(i + 1, max(mx, v))
    rec(1, 0)
    return out


def rent_num(T, lab, nb, N):
    """The Ω rent at one view, as an INTEGER numerator over N: the mass the best
    deterministic coarse map fails to carry, times N.  Integer arithmetic — the
    sorted rent multiset is the histogram of these, and there are at most N + 1
    possible values, which is what makes N3 affordable at n = 5."""
    cnt = {}
    for s in range(N):
        k = lab[s] * nb + lab[T[s]]
        cnt[k] = cnt.get(k, 0) + 1
    best = [0] * nb
    for k, v in cnt.items():
        a = k // nb
        if v > best[a]:
            best[a] = v
    return N - sum(best)


def viewindexed_separates(members, repB, labs, vnb, N, prefix=3000):
    """Is orbit A's rep separated from orbit B's rep by the VIEW-INDEXED rent
    profile, up to gauge?  Exact: quantify over every member of A's orbit (the
    conjugates) and ask whether any has the identical view-by-view profile as
    B.  Fast path: profiles that already differ on a prefix of the lattice
    differ, full stop; only a conjugate agreeing on the whole prefix is checked
    against the whole lattice."""
    prof_pref = [rent_num(repB, labs[v], vnb[v], N) for v in range(min(prefix, len(labs)))]
    survivors = []
    for TA in members:
        if all(rent_num(TA, labs[v], vnb[v], N) == prof_pref[v]
               for v in range(len(prof_pref))):
            survivors.append(TA)
    if not survivors:
        return True
    profB = [rent_num(repB, labs[v], vnb[v], N) for v in range(len(labs))]
    for TA in survivors:
        if all(rent_num(TA, labs[v], vnb[v], N) == profB[v] for v in range(len(labs))):
            return False
    return True


def n_closed_views(T, labs, k):
    """The count of views at which T closes: partitions whose blocks T permutes
    (rent exactly zero).  This is S6's quantity — accidental closure."""
    tot = 0
    for lab in labs:
        img = {}
        ok = True
        for s in range(k):
            a, b = lab[s], lab[T[s]]
            if img.setdefault(a, b) != b:
                ok = False
                break
        if ok:
            tot += 1
    return tot


def perm_order(T):
    x, k = tuple(range(len(T))), 0
    while True:
        x = tuple(T[i] for i in x)
        k += 1
        if x == tuple(range(len(T))):
            return k


# =========================================================== the derived law
def mechanism_fraction_closed_form(n):
    """A CONSEQUENCE of the staked mechanism, not independent evidence: the
    selected count is sum over derangements m of 2^(n - #cycles(m)), so the
    fraction is [x^n] (1-x)^(-1/2) e^(-x/2).  Reported because a fraction that
    falls on three points is weaker than a fraction with a law that falls to
    zero — and the law is checked against the enumeration at every n."""
    N = n + 1
    a = [F(0)] * N            # (1-x)^(-1/2)
    a[0] = F(1)
    for k in range(1, N):
        a[k] = a[k - 1] * F(2 * k - 1, 2 * k)
    b = [F(0)] * N            # e^(-x/2)
    b[0] = F(1)
    for k in range(1, N):
        b[k] = b[k - 1] * F(-1, 2 * k)
    return sum(a[k] * b[n - k] for k in range(N))


