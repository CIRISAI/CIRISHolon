        void(all(ncl[label[T]] == n_closed_views(T, labs, N)
                 for (T, m, c) in fam[:min(len(fam), 40)]),
             f"n={n}: the fused view sweep disagrees with the direct closed count")
        # N3: sorted-rent-multiset collisions between DISTINCT orbits.  The
        # multiset is exactly the histogram, so equality of histograms is the
        # collision test, with no floating point anywhere.
