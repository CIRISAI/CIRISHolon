            lab, nb, ty = labs[vi], vnb[vi], vtype[vi]
            for lb in rep_lbls:
                r = rent_num(reps[lb][0], lab, nb, N)
                hist_plain[lb][r] = hist_plain[lb].get(r, 0) + 1
                key = (ty, r)
