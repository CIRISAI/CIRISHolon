def pow_step(W, j):
    x = W["idp"].copy()
    for _ in range(j):
        x = W["step"][x]
    return x


def gauge_invariant_view(view, GAUGE):
    return all(np.array_equal(view[g], view) for g in GAUGE)


def run_rung(W, fam, k, want_control):
    view = W["V"][k]
    N = W["N"]
    idp = W["idp"]
    # An empty-vocabulary verdict depends only on the two step-powers, because
    # the view is gauge-invariant and the gauge commutes with the step — both
    # CHECKED here, never assumed.  That collapses 480x480 pairs to at most
    # (#divisors)^2 distinct questions at the coarse rungs, where the vocabulary
    # is empty and the rho-chain is otherwise thousands of nodes long.
    if int(view.max()) == 0:
        # A0, analytically: one block, so no rho can ever fail to preserve the
        # view and nothing is separable.  |Ident| is the whole family and the
        # selected set is empty -- computed here as a fact, not skipped.
        return dict(sel=[], idents={i: list(range(len(fam))) for i in range(len(fam))},
                    voids=0, ngroups=1, maxgroup=len(fam), ctrl_ok=True,
                    ctrl_n=1, ctrl_scored=0, knobcounts={})
    ginv = gauge_invariant_view(view, W["GAUGE"])
    # With a gauge-invariant view, view o (gauge_r step^d)^k = view o step^(dk),
    # so the whole empty-vocabulary chain is a function of the step-power alone.
    # Canonicalise the readings view o step^j ONCE per rung (exact ids, not
    # hashes) and every such verdict becomes an integer comparison.
    seqids = None
    if ginv:
        L = W["ordstep"]
        idmap, seqids = {}, []
        x = idp.copy()
        for _ in range(L):
            b = view[x].tobytes()
            seqids.append(idmap.setdefault(b, len(idmap)))
            x = W["step"][x]
        # view o T^k = view o step^(dk) follows from the two facts already
        # checked above (the gauge commutes with the step, and the view is
        # gauge-blind).  It is load-bearing, so it is also CHECKED directly on a
        # sample — by canonical id, which costs one lookup rather than a
        # from-scratch power.
        for (lab, q) in fam[:4]:
            d, acc = lab[0], idp.copy()
            for kk in range(1, 4):
                acc = q[acc]
                got = idmap.get(view[acc].tobytes(), -1)
                void(got == seqids[(d * kk) % L],
                     f"{W['name']} A{k}: view o T^k != view o step^(dk)")
    void(ginv, f"{W['name']} A{k}: the view is not gauge-invariant")
    void(all(np.array_equal(g[W["step"]], W["step"][g]) for g in W["GAUGE"]),
         f"{W['name']}: the gauge action does not commute with the step")
    dcache = {}
    # group by the single-step reading: only within a group can anything be
    # indistinguishable, so only those pairs pay for a BFS
    groups = {}
    for i, (lab, p) in enumerate(fam):
        groups.setdefault(view[p].tobytes(), []).append(i)

    idents, voids = {}, 0
    knobcache = {}
    for key, members in groups.items():
        if len(members) == 1:
            idents[members[0]] = [members[0]]
            continue
        for i in members:
            if i not in knobcache:
                cyc, cid = knobs_partial_sections(fam[i][1], view, N)
                void(acts_are_bijections(cyc, fam[i][1]),
                     "an act carrier is not dynamics-invariant (act not bijective)")
                knobcache[i] = (cyc, cid, inv_perm(fam[i][1], N))
            out = []
            for j in members:
                if i == j:
                    out.append(j)
                    continue
                if ginv and not knobcache[i][0]:
                    key = (fam[i][0][0], fam[j][0][0])
                    if key not in dcache:
                        L = W["ordstep"]
                        d1, d2 = key
                        dcache[key] = any(
                            seqids[(d1 * kk) % L] != seqids[(d2 * kk) % L]
                            for kk in range(1, L + 1))
                    s = dcache[key]
                else:
                    s = separates(knobcache[i], fam[i][1], fam[j][1], view, N, idp)
                if s is None:
                    voids += 1
                    out.append(j)          # undecided; the CELL is voided below
                elif not s:
                    out.append(j)
            idents[i] = out
    sel = sorted(i for i in range(len(fam)) if len(idents[i]) == 1)

    # plant (ii): the T3 control, on the pairs where the dynamics IS closed
    ctrl_ok, ctrl_n, ctrl_scored = True, 0, 0
    if want_control:
        for i, (lab, p) in enumerate(fam):
            if not closed_at(p, view):
                continue
            same = [j for j, (l2, q) in enumerate(fam)
                    if np.array_equal(view[q], view[p])]
            if len(same) < 2:
                continue                   # vacuous sector; not a carrier
            ctrl_n += 1
            kv = knobs_view_aligned(p, view, N)
            void(all_bijective(kv, N), "a view-aligned control act is not bijective")
            # The PROOF that this vocabulary is powerless is Break.lean's T3; the
            # plant is a live CONTROL, so it is scored on a declared bounded
            # sample of the carrier's class (the whole class would be 480 dense
            # closures run to exhaustion at 2I, since T3 guarantees every one of
            # them terminates only by exhausting).
            for j in same[:CTRL_SAMPLE]:
                if separates_dense(kv, p, fam[j][1], view, N, idp):
                    ctrl_ok = False
            ctrl_scored += min(len(same), CTRL_SAMPLE)
            break                          # one carrier with a nonzero sector
    return dict(sel=sel, idents=idents, voids=voids, ngroups=len(groups),
                maxgroup=max(len(v) for v in groups.values()),
                ctrl_ok=ctrl_ok, ctrl_n=ctrl_n, ctrl_scored=ctrl_scored,
                knobcounts={i: len(knobcache[i][0]) for i in knobcache})


