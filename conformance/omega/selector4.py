def refines(fine, coarse):
    m = {}
    for f, c in zip(fine.tolist(), coarse.tolist()):
        if m.setdefault(f, c) != c:
            return False
    return True


def build_world(name, MUL, INV):
    n = MUL.shape[0]
    N = n * n
    A = np.arange(N) % n
    B = np.arange(N) // n
    IDX = lambda a, b: a + n * b
    ident_g = int(next(g for g in range(n) if (MUL[g] == np.arange(n)).all()))

    comm = MUL[MUL[A, B], MUL[INV[A], INV[B]]]
    CLS = np.full(n, -1)
    reps, lab = [], 0
    for g in range(n):
        if CLS[g] >= 0:
            continue
        for h in {int(MUL[MUL[x, g], INV[x]]) for x in range(n)}:
            CLS[h] = lab
        reps.append(g)
        lab += 1
    ncls = lab

    T_MAP = IDX(A, MUL[A, B])
    S_MAP = IDX(B, MUL[MUL[B, A], INV[B]])
    step = S_MAP[T_MAP].astype(np.int32)
    void(len(set(step.tolist())) == N, f"{name}: the step is not bijective")

    orb = np.full(N, -1)
    lab = 0
    for i in range(N):
        if orb[i] >= 0:
            continue
        stack = [i]
        while stack:
            j = stack.pop()
            if orb[j] >= 0:
                continue
            orb[j] = lab
            a, b = int(A[j]), int(B[j])
            for x in range(n):
                k = int(IDX(MUL[MUL[x, a], INV[x]], MUL[MUL[x, b], INV[x]]))
                if orb[k] < 0:
                    stack.append(k)
        lab += 1

    R = [np.zeros(N, np.int64), (comm == ident_g).astype(np.int64), CLS[comm],
         CLS[A] * ncls + CLS[B], orb]

    def join(k):
        key, out = {}, np.zeros(N, np.int64)
        for i in range(N):
            t = tuple(int(R[j][i]) for j in range(k + 1))
            if t not in key:
                key[t] = len(key)
            out[i] = key[t]
        return out
    V = [join(k) for k in range(5)]
    for k in range(4):
        void(refines(V[k + 1], V[k]),
             f"{name}: acuity ladder is not a chain of coarsenings at A{k}->A{k+1}")

    GAUGE = [IDX(MUL[MUL[g, A], INV[g]], MUL[MUL[g, B], INV[g]]).astype(np.int32)
             for g in range(n)]
    for g in range(n):
        void(len(set(GAUGE[g].tolist())) == N, f"{name}: gauge action not bijective")

    ordstep, x, idp = 1, step.copy(), np.arange(N, dtype=np.int32)
    while not np.array_equal(x, idp):
        x = step[x]
        ordstep += 1
    return dict(name=name, n=n, N=N, step=step, V=V, GAUGE=GAUGE, reps=reps,
                ncls=ncls, ordstep=ordstep, idp=idp, ident_g=ident_g)


def divisors(m):
    return sorted(d for d in range(1, m + 1) if m % d == 0)


def family(W):
    """The declared candidate family: one canonical generator per cyclic
    subgroup of <step>, dressed by one representative per gauge orbit."""
    out, seen = [], set()
    powers = {}
    for d in divisors(W["ordstep"]):
        x = W["idp"].copy()
        for _ in range(d):
            x = W["step"][x]
        powers[d] = x.astype(np.int32)
    for d in divisors(W["ordstep"]):
        for r in W["reps"]:
            perm = W["GAUGE"][r][powers[d]].astype(np.int32)
            key = perm.tobytes()
            if key in seen:
                continue
            seen.add(key)
            out.append(((d, r), perm))
    return out


# ==================================================== acts and the separation
def cycles_of(perm, N):
    seen = np.zeros(N, bool)
    out = []
    pl = perm.tolist()
    for i in range(N):
        if seen[i]:
            continue
        c, j = [], i
        while not seen[j]:
            seen[j] = True
            c.append(j)
            j = pl[j]
        out.append(c)
    return out


def knobs_partial_sections(perm, view, N):
    """The atomic acts: fiber-injective cycles of the dynamics.

    Returned SPARSELY, as the carrier cycles themselves plus a per-state cycle
    label, never as materialised permutations.  a_P is the identity off P, so
    conjugating by it touches only P and rho^-1(P) — O(|P|) instead of O(N) —
    and since the cycles are DISJOINT, expanding every act at a search node
    costs O(N) in total rather than O(N x #acts).  At 2I's A4 that is the
    difference between 7680 arrays of 14400 int32 (442 MB, and 3 s per pair)
    and one label array.  The ACTS are unchanged; only the representation is."""
    vl = view.tolist()
    cyc_id = np.full(N, -1, dtype=np.int32)
    out = []
    for c in cycles_of(perm, N):
        if len(c) == 1:
            continue          # a fixed point's act IS the identity: no new words
        fs = [vl[s] for s in c]
        if len(set(fs)) == len(fs):
            arr = np.array(c, dtype=np.int32)
            cyc_id[arr] = len(out)
            out.append(arr)
    return out, cyc_id


def knobs_view_aligned(perm, view, N):
    """Plant (ii)'s control vocabulary: apply the dynamics on one CYCLE of view
    blocks, identity elsewhere.  A single block is NOT usable — the dynamics
    carries it off itself, so 'apply T on one block' is not a bijection and the
    rho-closure (which inverts acts) would be reading garbage.  A cycle of
    blocks under the induced block permutation IS invariant, so the act is a
    bijection, and it is view-covariant (its block action is that cycle), hence
    gauge-safe by Break.lean T3 wherever the dynamics is closed."""
    nb = int(view.max()) + 1
    blk = {}
    for a_, b_ in zip(view.tolist(), view[perm].tolist()):
        blk.setdefault(a_, b_)
    out, seen = [], set()
    for b in range(nb):
        if b in seen:
            continue
        cyc, j = [], b
        while j not in seen:
            seen.add(j)
            cyc.append(j)
            j = blk.get(j, j)
        m = np.isin(view, np.array(cyc))
        a = np.arange(N, dtype=np.int32)
        a[m] = perm[m]
        out.append(a.astype(np.int32))
    return out


def inv_perm(p, N):
    q = np.empty(N, dtype=np.int32)
    q[p] = np.arange(N, dtype=np.int32)
    return q


def all_bijective(perms, N):
    return all(len(set(p.tolist())) == N for p in perms)


def acts_are_bijections(cycles, perm):
    """a_P is a bijection exactly when P is T-invariant; the carriers are
    T-cycles, so this is checked rather than assumed (M-NONBIJECTIVE-STEP)."""
    return all(np.array_equal(np.sort(perm[c]), np.sort(c)) for c in cycles)


def separates(act, T, Tp, view, N, idp):
    """Exact over ALL experiment words (the rho-closure), no length cut.

    `act` is (cycles, cyc_id, Tinv) for the HOME world.  Returns True/False, or
    None if the declared node budget is exhausted (VOID, never a guess)."""
    if int(view.max()) == 0:
        return False                      # a constant view separates nothing, ever
    if not np.array_equal(view[Tp], view[T]):
        return True                       # the single-step word already splits
    cycles, cyc_id, Tinv = act
    if not cycles:
        # EMPTY VOCABULARY.  The closure is then the chain rho_k = T'^k T^-k, so
        # separation reduces to  exists k >= 1 : view o T'^k != view o T^k.
        a, b, k = T, Tp, 1
        while k < BUDGET:
            if not np.array_equal(view[a], view[b]):
                return True
            if np.array_equal(a, idp) and np.array_equal(b, idp):
                return False
            a, b, k = T[a], Tp[b], k + 1
        return None
    seen = {idp.tobytes()}
    stack = [idp]
    while stack:
        rho = stack.pop()
        if not np.array_equal(view[rho], view):
            return True
        nxt = [Tp[rho[Tinv]]]
        rhoinv = inv_perm(rho, N)
        for ci, P in enumerate(cycles):
            # rho' = a_P o rho o a_P^-1 differs from rho only on P u rho^-1(P)
            xs = np.unique(np.concatenate((P, rhoinv[P])))
            y = np.where(cyc_id[xs] == ci, Tinv[xs], xs)
            z = rho[y]
            newv = np.where(cyc_id[z] == ci, T[z], z)
            if np.array_equal(newv, rho[xs]):
                continue                  # the act commutes with rho
            r = rho.copy()
            r[xs] = newv
            nxt.append(r)
        for r in nxt:
            k = r.tobytes()
            if k not in seen:
                if len(seen) >= BUDGET:
                    return None
                seen.add(k)
                stack.append(r)
    return False


def separates_dense(knobs, T, Tp, view, N, idp):
    """The same exact rho-closure for plant (ii)'s materialised control acts,
    whose carriers are unions of view blocks rather than single cycles."""
    if not np.array_equal(view[Tp], view[T]):
        return True
    Tinv = inv_perm(T, N)
    kinv = [inv_perm(a, N) for a in knobs]
    seen = {idp.tobytes()}
    stack = [idp]
    while stack:
        rho = stack.pop()
        if not np.array_equal(view[rho], view):
            return True
        nxt = [Tp[rho[Tinv]]] + [a[rho[ai]] for a, ai in zip(knobs, kinv)]
        for r in nxt:
            k = r.tobytes()
            if k not in seen:
                if len(seen) >= BUDGET:
                    return None
                seen.add(k)
                stack.append(r)
    return False


def closed_at(perm, view):
    """Is the dynamics closed at this view (rent zero)?"""
    m = {}
    for a, b in zip(view.tolist(), view[perm].tolist()):
        if m.setdefault(a, b) != b:
            return False
    return True


