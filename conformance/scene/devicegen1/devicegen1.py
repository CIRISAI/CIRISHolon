def key(table, size, cell, building, kids):
    return (((table * 8 + size) * 32 + cell) * 4 + building) * 4 + kids


def ppm(wts):
    w = np.asarray(wts, dtype=float)
    if w.sum() <= 0:
        return None
    p = np.floor(1e6 * w / w.sum()).astype(np.int64)
    p[int(np.argmax(p))] += 1_000_000 - p.sum()
    return p.tolist()


def derive(D):
    """Fields the generator and the scoring share."""
    F = {}
    F["size"] = np.clip(D["members"], 1, 7).astype(int)
    F["s5"] = np.minimum(F["size"], 5)
    F["bld"] = np.where(np.isin(D["housing"], [4, 5]), 1, 0)
    F["adults"] = np.nan_to_num(D["adults"]).astype(int)
    F["seniors"] = np.nan_to_num(D["seniors"]).astype(int)
    F["children"] = np.nan_to_num(D["children"]).astype(int)
    F["conn"] = np.where(D["broadband"], 0, np.where(np.isin(D["internet"], [1, 2]), 1, 2))
    comp = (D["laptop"] + D["desktop"] + D["tablet"]) > 0
    spk = (D["streaming device"] + D["smart speaker"]) > 0
    F["comp"], F["spk"] = comp.astype(int), spk.astype(int)
    F["cell"] = F["conn"] * 4 + F["comp"] * 2 + F["spk"]
    F["kids"] = (F["children"] > 0).astype(int)
    F["senior_any"] = (F["seniors"] > 0).astype(int)
    F["phones"] = np.minimum(D["smartphone"], 20).astype(int)
    F["counts"] = np.stack([np.minimum(D[k], 8).astype(int) for k in KINDS8], 1)
    tv = np.where(D["tvhours"] == 0.5, 1, np.where(D["tvhours"] < 0, 0, D["tvhours"]))
    F["tv"] = np.clip(np.nan_to_num(tv), 0, 24).astype(int)
    F["athome"] = np.clip(np.nan_to_num(D["athome"]), 0, 5).astype(int)
    return F


def fit_phone_rates(F, w, m, rng):
    """Per-person smartphone shares (0, 1, 2) by group and connection."""
    rows = {}
    X = np.stack([F["adults"], F["seniors"], F["children"]], 1).astype(float)
    rates = np.zeros((3, 3))
    for c in range(3):
        mm = m & (F["conn"] == c) & (F["size"] < 7) & (F["children"] < 4)
        A = (X[mm] * w[mm][:, None]).T @ X[mm]
        rates[:, c] = np.clip(np.linalg.solve(A + 1e-9 * np.eye(3), (X[mm] * w[mm][:, None]).T @ F["phones"][mm]), 0.0, 1.6)
    persons = F["adults"] + F["seniors"] + F["children"]
    target = wmean((F["phones"] > persons).astype(float), w, m)

    def shares(q):
        out = np.zeros((3, 3, 3))
        for g in range(3):
            for c in range(3):
                r = rates[g, c]
                p2 = min(q * r, r / 2)
                p1 = max(r - 2 * p2, 0.0)
                p1 = min(p1, 1 - p2)
                out[g, c] = [max(1 - p1 - p2, 0), p1, p2]
        return out

    def over(q):
        sh = shares(q)
        idx = np.where(m)[0]
        tot = np.zeros(len(idx))
        for g, col in enumerate(("adults", "seniors", "children")):
            n = F[col][idx]
            for c in range(3):
                sel = F["conn"][idx] == c
                p = sh[g, c]
                k = int(n[sel].max()) if sel.any() else 0
                for j in range(k):
                    has = n[sel] > j
                    tot[np.where(sel)[0][has]] += rng.choice(3, size=int(has.sum()), p=p / p.sum())
        return float(wmean((tot > persons[idx]).astype(float), w[idx]))
    lo, hi = 0.0, 0.5
    for _ in range(12):
        mid = (lo + hi) / 2
        if over(mid) < target:
            lo = mid
        else:
            hi = mid
    q = (lo + hi) / 2
    sh = shares(q)
    for g in range(3):
        for c in range(3):
            rows[key(12, g, c, 0, 0)] = ppm(sh[g, c])
    return rows, {"rates_by_group_and_connection": rates.tolist(), "q_two_phones": q, "target_share_more_phones_than_persons": target}


def fit_tables(F, w, m, rng, min_n=30):
    rows = {}
    info = {"strata_written": {}, "min_records": min_n}
    for s in range(1, 8):
        for b in (0, 1, ANY):
            mm = m & (F["size"] == s) & ((F["bld"] == b) if b != ANY else True)
            if b != ANY and mm.sum() < min_n:
                continue
            code = F["adults"][mm] * 100 + F["seniors"][mm] * 10 + F["children"][mm]
            u = np.unique(code)
            p = ppm([w[mm][code == c].sum() for c in u])
            rows[key(0, s, 0, b, 0)] = [x for pair in zip(u.tolist(), p) for x in pair]
    for s in range(1, 6):
        for b in (0, 1, ANY):
            mm = m & (F["s5"] == s) & ((F["bld"] == b) if b != ANY else True)
            if b != ANY and mm.sum() < min_n:
                continue
            rows[key(1, s, 0, b, 0)] = ppm([w[mm & (F["cell"] == c)].sum() for c in range(12)])
        mm = m & (F["s5"] == s)
        tvm = mm & (F["counts"][:, 3] > 0)
        rows[key(10, s, 0, 0, 0)] = ppm([w[tvm & (F["tv"] == h)].sum() for h in range(25)])
        rows[key(11, s, 0, 0, 0)] = ppm([w[mm & (F["athome"] == h)].sum() for h in range(6)])
    nlev = [0, 0, 0, 0, 0]
    for k in range(8):
        cnt = F["counts"][:, k]
        for s in range(1, 6):
            ms = m & (F["s5"] == s)

            def put(kk, mm, lvl, force=False):
                if mm.sum() >= min_n or force:
                    p = ppm([w[mm & (cnt == v)].sum() for v in range(9)])
                    if p is not None:
                        rows[kk] = p
                        nlev[lvl] += 1
            put(key(2 + k, s, 18, ANY, ANY), ms, 4, True)
            for conn in range(3):
                for comp in range(2):
                    put(key(2 + k, s, 12 + conn * 2 + comp, ANY, ANY), ms & (F["conn"] == conn) & (F["comp"] == comp), 3)
            for c in range(12):
                mc = ms & (F["cell"] == c)
                put(key(2 + k, s, c, ANY, ANY), mc, 2)
                for b in (0, 1):
                    mb = mc & (F["bld"] == b)
                    put(key(2 + k, s, c, b, ANY), mb, 1)
                    for kd in (0, 1):
                        put(key(2 + k, s, c, b, kd), mb & (F["kids"] == kd), 0)
    info["histogram_rows_by_fallback_level"] = nlev
    pr, pinfo = fit_phone_rates(F, w, m, rng)
    rows.update(pr)
    info["phones"] = pinfo
    return rows, info


def write_tables(rows, path):
    with open(path, "w") as f:
        for k in sorted(rows):
            f.write("%d %s\n" % (k, " ".join(str(int(v)) for v in rows[k])))


def gen(binary, table_path, seeds, persons, building):
    inp = "".join("%d %d %d\n" % (s, p, b) for s, p, b in zip(seeds, persons, building))
    out = subprocess.run([binary, table_path], input=inp, capture_output=True, text=True, check=True).stdout.split("\n")
    n = len(seeds)
    A = np.array([l.split() for l in out[:n]], dtype=np.int64)
    digest = out[n].split()[1]
    return A, digest          # columns: adults seniors children ph0 ph1 ph2 c0..c7 conn tv athome


def have_nothing_ratio(nocomp, nofix, w):
    pa, pb, pab = wmean(nocomp.astype(float), w), wmean(nofix.astype(float), w), wmean((nocomp & nofix).astype(float), w)
    return pab / (pa * pb), pab, pa, pb


def rival_draw(F, w, fit, score, rng, seeds=SEEDS):
    """Each kind drawn ALONE given pooled size, building, any child, any senior. Returns
    the rival's have-nothing ratio over the SCORE households."""
    idx = np.where(score)[0]
    strat = F["s5"] * 8 + F["bld"] * 4 + F["kids"] * 2 + F["senior_any"]
    nocomp = np.ones((len(idx), seeds), dtype=bool)
    nofix = np.zeros((len(idx), seeds), dtype=bool)
    for s in np.unique(strat[idx]):
        sel = np.where(strat[idx] == s)[0]
        mf = fit & (strat == s)
        if mf.sum() < 30:
            mf = fit & (F["s5"] == s // 8)
        for kcol in (0, 1, 2):
            p0 = wmean((F["counts"][mf, kcol] == 0).astype(float), w[mf])
            nocomp[sel] &= rng.random((len(sel), seeds)) < p0
        pf = wmean((F["conn"][mf] != 0).astype(float), w[mf])
        nofix[sel] = rng.random((len(sel), seeds)) < pf
    ww = np.repeat(w[idx][:, None], seeds, 1)
    return have_nothing_ratio(nocomp.ravel(), nofix.ravel(), ww.ravel())


def std_contrast(vals, F, w, m, mix):
    """Size-standardised relative difference, apartment against house."""
    gi = np.minimum(F["size"], 4) - 1
    a = sum(mix[i] * wmean(vals, w, m & (gi == i) & (F["bld"] == 0)) for i in range(4))
    b = sum(mix[i] * wmean(vals, w, m & (gi == i) & (F["bld"] == 1)) for i in range(4))
    return (b - a) / ((a + b) / 2)


