def synth_survey(rng, n=24000, cluster=0.0, by_building=False):
    """A synthetic survey in this script's derived form."""
    size = rng.choice(np.arange(1, 8), n, p=[.28, .34, .15, .12, .06, .03, .02])
    bld = (rng.random(n) < np.where(size <= 2, 0.35, 0.12)).astype(int)
    children = np.where(size >= 3, rng.binomial(np.minimum(size - 1, 3), 0.55), 0)
    seniors = np.where(rng.random(n) < 0.25, np.minimum(size - children, 1 + (rng.random(n) < 0.3)), 0)
    adults = size - children - seniors
    # by_building: the have-nothing households are exactly the one-person apartments, so
    # pooled size and building explain the joint wholly and nothing is left for a cell
    have_not = ((bld == 1) & (size == 1)) if by_building else (rng.random(n) < cluster)
    conn = np.where(have_not, rng.choice([1, 2], n), np.where(rng.random(n) < 0.85, 0, 1))
    counts = np.stack([rng.poisson(lam, n) for lam in (1.3, 0.5, 1.0, 2.2, 1.2, 1.0, 0.5, 0.6)], 1)
    counts[have_not, :3] = 0
    counts[:, 1] = np.where(bld == 1, rng.binomial(counts[:, 1], 0.5), counts[:, 1])
    counts = np.minimum(counts, 8)
    F = {"size": size, "s5": np.minimum(size, 5), "bld": bld, "adults": adults, "seniors": seniors, "children": children, "conn": conn,
         "comp": (counts[:, :3].sum(1) > 0).astype(int), "spk": ((counts[:, 5] + counts[:, 7]) > 0).astype(int),
         "kids": (children > 0).astype(int), "senior_any": (seniors > 0).astype(int),
         "phones": rng.binomial(adults, 0.95) + rng.binomial(seniors, 0.7) + rng.binomial(children, 0.5),
         "counts": counts, "tv": rng.integers(0, 12, n), "athome": rng.integers(0, 6, n)}
    F["cell"] = F["conn"] * 4 + F["comp"] * 2 + F["spk"]
    return F, np.ones(n)


def plants(binary):
    rng = np.random.default_rng(21)
    res = {}
    with tempfile.TemporaryDirectory() as td:
        tp = os.path.join(td, "t.txt")
        # P-CELLS and P-CLUSTER: a have-nothing class unrelated to size, building or composition
        F, w = synth_survey(rng, cluster=0.09)
        n = len(w)
        fit = rng.random(n) < 0.5
        rows, _ = fit_tables(F, w, fit, rng)
        write_tables(rows, tp)
        idx = np.where(~fit)[0]
        seeds = np.arange(len(idx) * 4)
        A, _ = gen(binary, tp, seeds, np.repeat(F["size"][idx], 4), np.repeat(F["bld"][idx], 4))
        cellg = A[:, 14] * 4 + (A[:, 6:9].sum(1) > 0) * 2 + ((A[:, 11] + A[:, 13]) > 0)
        fr_g = np.bincount(cellg, minlength=12) / len(cellg)
        fr_s = np.bincount(F["cell"][idx], minlength=12) / len(idx)
        res["P-CELLS"] = float(np.abs(fr_g - fr_s).max()) < 0.01
        rg = have_nothing_ratio(A[:, 6:9].sum(1) == 0, A[:, 14] != 0, np.ones(len(A)))[0]
        rs = have_nothing_ratio(F["comp"][idx] == 0, F["conn"][idx] != 0, np.ones(len(idx)))[0]
        rr = rival_draw(F, w, fit, ~fit, rng)[0]
        res["P-CLUSTER"] = abs(rg - rs) < 0.25 * rs and rs > 2 and rr < 1.5
        res["P-CONSISTENT"] = bool(((A[:, 6:9].sum(1) > 0) == ((cellg // 2) % 2 == 1)).all())
        res["P-PERSONS"] = bool((A[:, :3].sum(1) == np.repeat(F["size"][idx], 4)).all())
        ph = A[:, 3:6].sum(1)
        res["P-TWOPHONES"] = bool((ph > A[:, :3].sum(1)).any())
        A2, _ = gen(binary, tp, seeds[:200], np.repeat(F["size"][idx], 4)[:200], np.repeat(F["bld"][idx], 4)[:200])
        res["P-SEED"] = bool((A2 == A[:200]).all())
        # P-COVARIATE: the have-nothing share is explained wholly by building
        F, w = synth_survey(rng, cluster=0.09, by_building=True)
        fit = rng.random(len(w)) < 0.5
        idx = np.where(~fit)[0]
        rs = have_nothing_ratio(F["comp"][idx] == 0, F["conn"][idx] != 0, np.ones(len(idx)))[0]
        rr = rival_draw(F, w, fit, ~fit, rng)[0]
        res["P-COVARIATE"] = bool(abs(rr - rs) < 0.15 * rs and rs > 1.5)
        res["_covariate_ratios_survey_rival"] = [float(rs), float(rr)]
        # P-THIN: a stratum with 12 records is not written at its own level
        F, w = synth_survey(rng, n=3000)
        m = np.ones(len(w), dtype=bool)
        rows, info = fit_tables(F, w, m, rng)
        thin = [(s, c, b, kd) for s in range(1, 6) for c in range(12) for b in (0, 1) for kd in (0, 1)
                if 0 < (m & (F["s5"] == s) & (F["cell"] == c) & (F["bld"] == b) & (F["kids"] == kd)).sum() < 30]
        res["P-THIN"] = bool(thin) and all(key(2, s, c, b, kd) not in rows for s, c, b, kd in thin) and key(2, 1, 18, ANY, ANY) in rows
    return res


