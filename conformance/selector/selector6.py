# budget exhaustion can never be recorded as a negative verdict.
MIN_DECIDED_RUNG = 3


class Refused(Exception):
    pass


class LabelAdapter:
    """refute_lib's RULE-B expects landscape_sweep's FiniteGroup interface;
    the census carries its own group object.  This adapts one to the other and
    nothing more -- it exposes only what RULE-B reads, so a construction tag
    cannot reach the label even by accident (there is none to reach)."""

    def __init__(self, MUL, INV, IDE, n):
        self.MUL = np.asarray(MUL, dtype=np.int64)
        self.INV = np.asarray(INV, dtype=np.int64)
        self.IDE = int(IDE)
        self.order = int(n)
        self._cls = None
        self._comm = None
        self._ord = None

    @property
    def classes(self):
        if self._cls is None:
            n, M, I = self.order, self.MUL, self.INV
            lab = [-1] * n
            out = []
            for g in range(n):
                if lab[g] >= 0:
                    continue
                orb = {int(M[M[x, g], I[x]]) for x in range(n)}
                for h in orb:
                    lab[h] = len(out)
                out.append(orb)
            self._cls = out
        return self._cls

    @property
    def commutator_subgroup(self):
        if self._comm is None:
            n, M, I = self.order, self.MUL, self.INV
            S = {int(M[M[a, b], M[I[a], I[b]]]) for a in range(n) for b in range(n)}
            changed = True
            while changed:
                changed = False
                new = {int(M[x, y]) for x in S for y in S} - S
                if new:
                    S |= new
                    changed = True
            self._comm = S
        return self._comm

    @property
    def element_orders(self):
        if self._ord is None:
            M, ide = self.MUL, self.IDE
            out = []
            for g in range(self.order):
                o, cur = 1, g
                while cur != ide:
                    cur = int(M[cur, g])
                    o += 1
                out.append(o)
            self._ord = out
        return self._ord


def build_family(W):
    """F(G) = {GAUGE[g] . step^d : g in G, d | ord(step)}, deduplicated, with
    its gauge-orbit partition.  A function of (MUL, INV) with no choices."""
    n = W["n"]
    divs = S4.divisors(W["ordstep"])
    powers, x, dset = {}, W["idp"].copy(), set(divs)
    for d in range(1, max(divs) + 1):
        x = W["step"][x]
        if d in dset:
            powers[d] = x.astype(np.int32)
    index, members, perms = {}, [], []
    for d in divs:
        for g in range(n):
            p = W["GAUGE"][g][powers[d]].astype(np.int32)
            key = p.tobytes()
            if key not in index:
                index[key] = len(members)
                members.append((d, g))
                perms.append(p)
    MUL, INV = W["MUL"], W["INV"]
    orbit_of = [-1] * len(members)
    reps, sizes = [], []
    ar = np.arange(n)
    for i, (d, g) in enumerate(members):
        if orbit_of[i] >= 0:
            continue
        orb = set()
        for x_ in range(n):
            gg = int(MUL[MUL[x_, g], INV[x_]])
            orb.add(index[W["GAUGE"][gg][powers[d]].astype(np.int32).tobytes()])
        lab = len(reps)
        for j in orb:
            orbit_of[j] = lab
        reps.append(i)
        sizes.append(len(orb))
    return members, perms, orbit_of, reps, sizes, powers


def run_group(W, members, perms, orbit_of, reps, sizes, powers, homes=None,
              deadline=None):
    """Per-rung selected sets.  Returns dict rung -> (sel_count, void_count) plus
    diagnostics.  `homes` overrides the orbit representatives (used by the
    orbit-constancy check)."""
    N, idp = W["N"], W["idp"]
    # The equivariance lemma has three hypotheses (SELECTOR6_DESIGN.md section 2).
    # Two are per-group facts and are CHECKED here rather than assumed; the third
    # (the view is gauge-invariant) is checked per rung below.  If either fails,
    # the gauge-orbit economy is not valid for this group and it must VOID rather
    # than be scored on an unproved decomposition.
    for g in W["GAUGE"]:
        if not np.array_equal(g[W["step"]], W["step"][g]):
            raise Refused("gauge action does not commute with the step")
        if len(set(g.tolist())) != N:
            raise Refused("gauge action not bijective")
    F = len(members)
    is_home = np.zeros(F, bool)
    for i in (reps if homes is None else homes):
        is_home[i] = True
    out = {}
    bfs_calls = 0
    audits = []
    for k in range(5):
        view = W["V"][k]
        if int(view.max()) == 0:
            out[k] = dict(sel=0, voids=0, mode="analytic-A0", homes=len(reps))
            continue
        ginv = S4.gauge_invariant_view(view, W["GAUGE"])
        if not ginv:
            out[k] = dict(sel=None, voids=1, mode="VOID-view-not-gauge-invariant")
            continue
        # canonical ids for view o step^j, for the empty-vocabulary fast path
        L = W["ordstep"]
        idmap, seqids, x = {}, [], idp.copy()
        for _ in range(L):
            seqids.append(idmap.setdefault(view[x].tobytes(), len(idmap)))
            x = W["step"][x]
        dcache = {}

        groups = {}
        for i in range(F):
            groups.setdefault(view[perms[i]].tobytes(), []).append(i)

        sel_count, voids = 0, 0
        for mem in groups.values():
            if len(mem) == 1:
                for i in mem:
                    if is_home[i]:
                        sel_count += sizes[orbit_of[i]]
                continue
            for i in mem:
                if not is_home[i]:
                    continue
                if deadline and time.time() > deadline:
                    raise Refused("GROUP_WALL")
                cyc, cid = S4.knobs_partial_sections(perms[i], view, N)
                if not S4.acts_are_bijections(cyc, perms[i]):
                    raise Refused("act carrier not dynamics-invariant")
                act = (cyc, cid, S4.inv_perm(perms[i], N))
                alone, void_here = True, False
                for j in mem:
                    if i == j:
                        continue
                    if ginv and not cyc:
                        key = (members[i][0], members[j][0])
                        if key not in dcache:
                            d1, d2 = key
                            dcache[key] = any(
                                seqids[(d1 * kk) % L] != seqids[(d2 * kk) % L]
                                for kk in range(1, L + 1))
                        s = dcache[key]
                        if len(audits) < CHEAP_AUDIT:
                            full = S4.separates(act, perms[i], perms[j], view, N, idp)
                            if full is not None:
                                audits.append((s, full))
                    else:
                        bfs_calls += 1
                        if bfs_calls > GROUP_BFS_BUDGET:
                            raise Refused("GROUP_BFS_BUDGET")
                        s = S4.separates(act, perms[i], perms[j], view, N, idp)
                    if s is None:
                        void_here = True
                        break
                    if not s:
                        alone = False
                        break
                if void_here:
                    voids += 1
                elif alone:
                    sel_count += sizes[orbit_of[i]]
        out[k] = dict(sel=sel_count, voids=voids, mode="measured",
                      homes=int(is_home.sum()))
    return out, bfs_calls, audits


def verdict(per_rung, Fsize):
    """SELECT(G) at the finest decided rung, with ruling 3's refusal.

    Ruling 3: a VOID at rung k removes rung k AND EVERY FINER RUNG.  So the
    surviving rungs are 0..(coarsest voiding rung - 1) -- NOT "the finest rung
    that happens to have no VOIDs".  The distinction bites when a coarse rung
    voids and a finer one does not: taking the finer one would report a verdict
    computed above a rung the run could not decide.
    """
    kstar = 4
    for k in range(5):
        r = per_rung.get(k)
        if r is None or r["sel"] is None or r["voids"] > 0:
            kstar = k - 1
            break
    if kstar < MIN_DECIDED_RUNG:
        return None, kstar, None
    sel = per_rung[kstar]["sel"]
    return (0 < sel < Fsize), kstar, sel
